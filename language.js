// Apply language to page
function applyLanguage(lang) {
  const langData = translations[lang] || translations.en;
  
  // Update page language attribute
  document.documentElement.lang = lang;
  
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    if (langData[key]) {
      element.textContent = langData[key];
    }
  });
  
  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.dataset.i18nPlaceholder;
    if (langData[key]) {
      element.placeholder = langData[key];
    }
  });
  
  console.log(`✓ Language changed to: ${lang}`);
}

// Initialize language switcher
document.addEventListener('DOMContentLoaded', function() {
  console.log('✓ Language switcher initializing...');
  
  const languageBtn = document.querySelector('.nav-language');
  console.log('Language button found:', !!languageBtn, languageBtn);
  
  if (!languageBtn) {
    console.error('❌ Language button not found - check if .nav-language class exists');
    return;
  }
  
  const navActions = languageBtn.closest('.nav-actions');
  console.log('Nav actions found:', !!navActions, navActions);
  
  if (!navActions) {
    console.error('❌ Nav actions element not found');
    return;
  }
  
  // Create language menu
  let languageMenu = navActions.querySelector('.language-menu');
  console.log('Existing language menu found:', !!languageMenu);
  
  if (!languageMenu) {
    languageMenu = document.createElement('ul');
    languageMenu.className = 'language-menu';
    languageMenu.innerHTML = `
      <li><a href="#" class="lang-option" data-lang="en">🇬🇧 English</a></li>
      <li><a href="#" class="lang-option" data-lang="es">🇪🇸 Español</a></li>
      <li><a href="#" class="lang-option" data-lang="fr">🇫🇷 Français</a></li>
      <li><a href="#" class="lang-option" data-lang="de">🇩🇪 Deutsch</a></li>
      <li><a href="#" class="lang-option" data-lang="pt">🇵🇹 Português</a></li>
      <li><a href="#" class="lang-option" data-lang="ja">🇯🇵 日本語</a></li>
      <li><a href="#" class="lang-option" data-lang="zh">🇨🇳 中文</a></li>
    `;
    navActions.appendChild(languageMenu);
    console.log('✓ Language menu created and added to DOM');
  }
  
  // Toggle menu on button click
  languageBtn.addEventListener('click', function(e) {
    e.preventDefault();
    e.stopPropagation();
    languageMenu.classList.toggle('active');
    console.log('✓ Button clicked - Menu active:', languageMenu.classList.contains('active'));
  });
  
  // Handle language selection
  languageMenu.querySelectorAll('.lang-option').forEach(option => {
    option.addEventListener('click', function(e) {
      e.preventDefault();
      e.stopPropagation();
      
      const selectedLang = this.dataset.lang;
      console.log('✓ Language selected:', selectedLang);
      
      // Update active state
      languageMenu.querySelectorAll('.lang-option').forEach(opt => {
        opt.classList.remove('active');
      });
      this.classList.add('active');
      
      // Save language preference
      localStorage.setItem('selectedLanguage', selectedLang);
      
      // Close menu
      languageMenu.classList.remove('active');
      
      // Apply language change
      applyLanguage(selectedLang);
    });
  });
  
  // Set initial active language
  const currentLang = localStorage.getItem('selectedLanguage') || 'en';
  const activeOption = languageMenu.querySelector(`[data-lang="${currentLang}"]`);
  if (activeOption) {
    activeOption.classList.add('active');
    console.log('✓ Initial language set to:', currentLang);
  }
  
  // Apply initial language
  applyLanguage(currentLang);
  
  // Close menu when clicking outside
  document.addEventListener('click', function(e) {
    if (!navActions.contains(e.target)) {
      languageMenu.classList.remove('active');
    }
  });
  
  console.log('✅ Language switcher ready - click the globe icon (🌐) to test!');
});
